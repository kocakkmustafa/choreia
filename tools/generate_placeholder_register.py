#!/usr/bin/env python3
"""Generates docs/design/PLACEHOLDER-REGISTER.md from `PLACEHOLDER(...)` code
markers. Never hand-edit the register — this script IS the register; a
hand-maintained list is the family's own named-expensive failure class
(bayat liste — a written claim nobody re-checks against the code that made it
true). Run after adding or resolving a marker:

    python3 tools/generate_placeholder_register.py

Marker format, left at the exact code location standing in for the missing
asset/copy/data/flow (coordinator directive, 2026-08-06, three lines at
once):

    // PLACEHOLDER(<category>): <what is missing> — unblocked by: <what it
    // is waiting for>

Categories: asset (image/photo) · copy (text) · data (content/measurement) ·
flow (a closed step, e.g. practice-with-the-beat). A marker with no
`unblocked by` clause fails this script on purpose — the parallel rule to
K10's "an ungraded lesson names a reason": a tracked gap with no named exit
is not tracked, it is just forgotten more slowly.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCAN_DIRS = ["lib"]
OUTPUT = REPO_ROOT / "docs" / "design" / "PLACEHOLDER-REGISTER.md"

MARKER_START = re.compile(r"^\s*//\s*PLACEHOLDER\((?P<category>\w+)\):\s*(?P<rest>.*)$")
COMMENT_CONT = re.compile(r"^\s*//\s?(?P<rest>.*)$")
UNBLOCKED = re.compile(r"unblocked by:\s*(?P<what>.+)$", re.IGNORECASE)

CATEGORIES = {
    "asset": "Asset — an image/photo the design calls for and content does not have yet",
    "copy": "Copy — user-facing text the design calls for and content does not have yet",
    "data": "Data — content or a measurement the design assumes and the engine/content does not carry yet",
    "flow": "Flow — a step or screen the design shows closed/empty on purpose",
}


@dataclass
class Entry:
    category: str
    file: str
    line: int
    text: str
    unblocked_by: str | None


def find_markers() -> list[Entry]:
    entries: list[Entry] = []
    for scan_dir in SCAN_DIRS:
        for path in sorted((REPO_ROOT / scan_dir).rglob("*.dart")):
            lines = path.read_text(encoding="utf-8").splitlines()
            i = 0
            while i < len(lines):
                m = MARKER_START.match(lines[i])
                if not m:
                    i += 1
                    continue
                category = m.group("category")
                parts = [m.group("rest").strip()]
                j = i + 1
                while j < len(lines):
                    cm = COMMENT_CONT.match(lines[j])
                    if not cm or MARKER_START.match(lines[j]):
                        break
                    parts.append(cm.group("rest").strip())
                    j += 1
                text = " ".join(p for p in parts if p)
                ub = UNBLOCKED.search(text)
                rel = str(path.relative_to(REPO_ROOT))
                entries.append(Entry(
                    category=category,
                    file=rel,
                    line=i + 1,
                    text=text,
                    unblocked_by=ub.group("what").strip() if ub else None,
                ))
                i = j
    return entries


def render(entries: list[Entry]) -> str:
    lines = [
        "<!-- GENERATED by tools/generate_placeholder_register.py. Do not hand-edit —",
        "     re-run the script after adding or resolving a PLACEHOLDER(...) marker. -->",
        "",
        "# Choreia — Placeholder Register",
        "",
        f"{len(entries)} placeholder marker(s) found in `lib/`, "
        f"{sum(1 for e in entries if e.unblocked_by is None)} missing a named "
        "`unblocked by` clause.",
        "",
        "Every entry here is a spot where the app does NOT show fake data — it shows",
        "nothing, or the real (partial) data, and this file is where the gap is named",
        "instead of forgotten. If a marker below has no unlock condition, that is a",
        "defect in the marker, not a stylistic choice — fix the comment, not this file.",
        "",
    ]
    if not entries:
        lines.append("_No PLACEHOLDER markers found in `lib/` as of the last run._")
        return "\n".join(lines) + "\n"

    by_cat: dict[str, list[Entry]] = {}
    for e in entries:
        by_cat.setdefault(e.category, []).append(e)

    for cat in sorted(by_cat, key=lambda c: (c not in CATEGORIES, c)):
        label = CATEGORIES.get(cat, f"{cat} (undeclared category)")
        lines.append(f"## {label}")
        lines.append("")
        for e in by_cat[cat]:
            lines.append(f"- **`{e.file}:{e.line}`** — {e.text}")
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    entries = find_markers()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(entries), encoding="utf-8")
    unnamed = [e for e in entries if e.unblocked_by is None]
    print(f"placeholder register: {len(entries)} marker(s) -> {OUTPUT.relative_to(REPO_ROOT)}")
    if unnamed:
        print(f"FAIL: {len(unnamed)} marker(s) have no 'unblocked by' clause:", file=sys.stderr)
        for e in unnamed:
            print(f"  {e.file}:{e.line}: {e.text}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
